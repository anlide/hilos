                languageCode: $parts[0],
                countryCode: isset($parts[1]) ? strtolower($parts[1]) : null,
                dateFormat: $row[self::KEY_DATE_FORMAT],
                timeFormat: $row[self::KEY_TIME_FORMAT],
                numberFormat: $row[self::KEY_NUMBER_FORMAT],
                phoneFormat: $row[self::KEY_PHONE_FORMAT],
                addressFormat: $row[self::KEY_ADDRESS_FORMAT],
                measurementSystem: $row[self::KEY_MEASUREMENT_SYSTEM],
                collation: $row[self::KEY_COLLATION],
            );
        }
    }

    /** @return iterable<DefaultLocaleDefinition> All source-country hints */
    public static function defaultLocales(): iterable
    {
        foreach (self::DEFAULT_LOCALES as $countryCode => $localeCode) {
            yield new DefaultLocaleDefinition($countryCode, $localeCode);
        }
    }

    /** @return iterable<CountryNameDefinition> All base country names */
    public static function countryNames(): iterable
    {
        foreach (self::COUNTRY_NAMES as $countryCode => $names) {
            foreach ($names as $languageCode => $name) {
                yield new CountryNameDefinition($countryCode, $languageCode, $name);
            }
        }
    }

    /**
     * @return string Lowercase SHA-256 digest of all five catalog groups
     * @throws JsonException When catalog data cannot be encoded as JSON
     */
    public static function fingerprint(): string
    {
        return I18nCatalogFingerprint::of(
            self::LANGUAGES,
            self::COUNTRIES,
            self::LOCALES,
            self::DEFAULT_LOCALES,
            self::COUNTRY_NAMES,
        );
    }
