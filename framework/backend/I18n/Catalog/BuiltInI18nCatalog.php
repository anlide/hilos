    /**
     * @param string $code Exact lowercase language code
     * @return ?LanguageDefinition Built-in language, or null when absent
     */
    public static function language(string $code): ?LanguageDefinition
    {
        $row = self::LANGUAGES[$code] ?? null;
        if ($row === null) {
            return null;
        }

        return new LanguageDefinition($code, $row[self::KEY_NATIVE_NAME], $row[self::KEY_RTL]);
    }

    /**
     * @param string $code Exact lowercase country code
     * @return ?CountryDefinition Built-in country, or null when absent
     */
    public static function country(string $code): ?CountryDefinition
    {
        $row = self::COUNTRIES[$code] ?? null;
        if ($row === null) {
            return null;
        }

        return new CountryDefinition($code, $row[self::KEY_CURRENCY_SYMBOL], $row[self::KEY_CURRENCY_CODE]);
    }

    /**
     * @param string $code Exact canonical locale code
     * @return ?LocaleDefinition Built-in locale, or null when absent
     */
    public static function locale(string $code): ?LocaleDefinition
    {
        $row = self::LOCALES[$code] ?? null;
        if ($row === null) {
            return null;
        }

        $parts = explode('-', $code, 2);

        return new LocaleDefinition(
            code: $code,
            languageCode: $parts[0],
            countryCode: isset($parts[1]) ? strtolower($parts[1]) : null,
            dateFormat: $row[self::KEY_DATE_FORMAT],
            timeFormat: $row[self::KEY_TIME_FORMAT],
            numberFormat: $row[self::KEY_NUMBER_FORMAT],
            phoneFormat: $row[self::KEY_PHONE_FORMAT],
            addressFormat: $row[self::KEY_ADDRESS_FORMAT],
            measurementSystem: $row[self::KEY_MEASUREMENT_SYSTEM],
            collation: $row[self::KEY_COLLATION],
        );
    }

    /**
     * A hint may name a country outside the 51 built-in countries or a locale
     * not present in the locale catalog. The consumer checks row availability.
     *
     * @param string $countryCode Exact lowercase source country code
     * @return ?string Suggested canonical locale code, or null when absent
     */
    public static function defaultLocale(string $countryCode): ?string
    {
        return self::DEFAULT_LOCALES[$countryCode] ?? null;
    }

    /**
     * @param string $countryCode Exact lowercase country code
     * @param string $languageCode Exact lowercase language code
     * @return ?string Base country name, or null when absent
     */
    public static function countryName(string $countryCode, string $languageCode): ?string
    {
        return self::COUNTRY_NAMES[$countryCode][$languageCode] ?? null;
    }

    /** @return iterable<LanguageDefinition> All built-in languages */
    public static function languages(): iterable
    {
        foreach (self::LANGUAGES as $code => $row) {
            yield new LanguageDefinition($code, $row[self::KEY_NATIVE_NAME], $row[self::KEY_RTL]);
        }
    }

    /** @return iterable<CountryDefinition> All built-in countries */
    public static function countries(): iterable
    {
        foreach (self::COUNTRIES as $code => $row) {
            yield new CountryDefinition($code, $row[self::KEY_CURRENCY_SYMBOL], $row[self::KEY_CURRENCY_CODE]);
        }
    }

